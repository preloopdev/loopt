"""``loopt_sdk``: author GitHub Actions workflows in Python.

The package is organised in three layers:

- :mod:`loopt_sdk.expr` -- ``${{ ... }}`` expressions, operators, built-in
  functions, and navigable contexts (``github``, ``secrets``, ...).
- :mod:`loopt_sdk.core` -- ``run``/``uses`` steps, jobs, workflows, and
  ``JobRef``/``StepRef`` output references.
- :mod:`loopt_sdk.emit` -- prints the finished document as the one JSON line
  ``loopt gen`` consumes.

Generated projects import the copy vendored under ``.loopt/sdk/python``, so
no installation is required.
"""

