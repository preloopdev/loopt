fn checked_in_generated_typescript_is_fresh() {
    let files = generated_files();
    let out_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../sdk/typescript/src/generated");
    let stale = stale_files(&out_dir, &files)
        .unwrap_or_else(|error| panic!("inspecting `{}` must succeed: {error}", out_dir.display()));
    assert!(
        stale.is_empty(),
        "generated TypeScript at {} is stale: {stale:?}\nrun: cargo run -p loopt-sdkgen -- typescript",
        out_dir.display()
    );
}
