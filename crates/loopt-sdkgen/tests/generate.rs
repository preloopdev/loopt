#[test]
fn write_all_and_stale_files_round_trip() {
    let files = generated_files();
    let temp = TempDir::new("round-trip");
    let out_dir = temp.path().join("nested").join("generated");

    write_all(&out_dir, &files).expect("write_all must create the output directory");
    for file in &files {
        let written = fs::read_to_string(out_dir.join(&file.path))
            .unwrap_or_else(|error| panic!("reading `{}` must succeed: {error}", file.path));
        assert_eq!(
            written, file.content,
            "write_all must write the generated content of `{}` verbatim",
            file.path
        );
    }
    assert!(
        stale_files(&out_dir, &files)
            .expect("inspecting a freshly written directory must succeed")
            .is_empty(),
        "a fresh write must leave no stale files"
    );

    let tampered = out_dir.join("aliases.ts");
    let mut text = fs::read_to_string(&tampered).expect("reading aliases.ts must succeed");
    text.push_str("// tampered\n");
    fs::write(&tampered, text).expect("tampering with aliases.ts must succeed");
    assert_eq!(
        stale_files(&out_dir, &files).expect("inspecting a tampered directory must succeed"),
        vec!["aliases.ts".to_owned()],
        "only the edited file may be reported stale"
    );

    write_all(&out_dir, &files).expect("write_all must restore the edited file");
    assert!(
        stale_files(&out_dir, &files)
            .expect("inspecting the restored directory must succeed")
            .is_empty(),
        "rewriting must clear the stale file"
    );

    let absent = temp.path().join("absent");
    let mut missing =
        stale_files(&absent, &files).expect("a missing output directory must not be an error");
    missing.sort();
    let mut expected: Vec<String> = GENERATED_PATHS
        .iter()
        .map(|path| (*path).to_owned())
        .collect();
    expected.sort();
    assert_eq!(
        missing, expected,
        "a missing output directory must report every generated file as stale"
    );
}

