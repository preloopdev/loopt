#[test]
fn aliases_map_camel_case_names_to_exact_schema_keys() {
    let files = generated_files();
    let aliases = content(&files, "aliases.ts");

    let workflow_aliases: serde_json::Value =
        serde_json::from_str(json_initializer(aliases, "WORKFLOW_ALIASES"))
            .expect("WORKFLOW_ALIASES must be a valid JSON initialiser");
    let action_aliases: serde_json::Value =
        serde_json::from_str(json_initializer(aliases, "ACTION_ALIASES"))
            .expect("ACTION_ALIASES must be a valid JSON initialiser");

    assert_eq!(
        alias(&workflow_aliases, "job-factory", "runsOn"),
        Some("runs-on"),
        "job-factory must alias runsOn to runs-on"
    );
    assert_eq!(
        alias(&workflow_aliases, "job-factory", "timeoutMinutes"),
        Some("timeout-minutes"),
        "job-factory must alias timeoutMinutes to timeout-minutes"
    );
    assert_eq!(
        alias(&workflow_aliases, "permissions-mapping", "idToken"),
        Some("id-token"),
        "the permissions mapping must alias idToken to id-token"
    );

    for absent in [
        "job-env",
        "workflow-env",
        "workflow-job-with",
        "workflow-job-secrets-mapping",
        "jobs",
    ] {
        assert!(
            workflow_aliases.get(absent).is_none(),
            "`{absent}` declares no properties and must be absent from WORKFLOW_ALIASES"
        );
    }
    for absent in ["step-env", "step-with", "inputs", "outputs"] {
        assert!(
            action_aliases.get(absent).is_none(),
            "`{absent}` declares no properties and must be absent from ACTION_ALIASES"
        );
    }

    assert_eq!(
        workflow_aliases,
        expected_aliases(preloop_gha_schema::workflow()),
        "WORKFLOW_ALIASES must map every mapping definition with properties to its camelCase keys"
    );
    assert_eq!(
        action_aliases,
        expected_aliases(preloop_gha_schema::action()),
        "ACTION_ALIASES must map every mapping definition with properties to its camelCase keys"
    );
}

#[test]
fn workflow_types_encode_the_expected_shapes() {
    let files = generated_files();
    let workflow = content(&files, "workflow.ts");
    let schema = preloop_gha_schema::workflow();

    assert_eq!(
        workflow.lines().nth(2),
        Some(KIT_IMPORT),
        "workflow.ts must import the kit types before any declaration"
    );

    let factory = schema
        .get("job-factory")
        .expect("the workflow schema must define job-factory");
    let properties = match &factory.kind {
        Kind::Mapping { properties, .. } => properties,
        other => panic!("job-factory must be a mapping, found {other:?}"),
    };
    assert!(
        properties
            .get("runs-on")
            .expect("job-factory must declare runs-on")
            .required,
        "runs-on must be required for the required-property assertion below"
    );
    assert!(
        !properties
            .get("timeout-minutes")
            .expect("job-factory must declare timeout-minutes")
            .required,
        "timeout-minutes must be optional for the optional-property assertion below"
    );

    let job_factory = declaration_block(workflow, "export interface JobFactory {");
    let lines: Vec<&str> = job_factory.lines().collect();
    assert!(
        lines.iter().any(|line| line.starts_with("  runsOn: ")),
        "JobFactory must declare runsOn as a required property"
    );
    assert!(
        lines
            .iter()
            .any(|line| line.starts_with("  timeoutMinutes?: ")),
        "JobFactory must declare timeoutMinutes as an optional property"
    );

    let timeout_index = lines
        .iter()
        .position(|line| line.starts_with("  timeoutMinutes?: "))
        .expect("JobFactory must declare timeoutMinutes");
    let timeout_doc = lines
        .get(timeout_index.wrapping_sub(1))
        .expect("the timeoutMinutes property must be preceded by a TSDoc line");
    assert!(
        timeout_doc.trim_start().starts_with("/**") && timeout_doc.trim_end().ends_with("*/"),
        "the timeoutMinutes property must be preceded by a TSDoc line, found `{timeout_doc}`"
    );
    let timeout_description = properties
        .get("timeout-minutes")
        .expect("job-factory must declare timeout-minutes")
        .description
        .as_deref()
        .expect("timeout-minutes must carry a description for the TSDoc assertion below");
    assert!(
        timeout_doc.contains(timeout_description),
        "the timeoutMinutes TSDoc must carry the property description, found `{timeout_doc}`"
    );

    let closing = lines
        .iter()
        .rposition(|line| *line == "}")
        .expect("the JobFactory interface must close with a brace at column zero");
    let last_member = lines[..closing]
        .iter()
        .rev()
        .find(|line| !line.trim().is_empty())
        .copied()
        .expect("the JobFactory interface must have members");
    assert_eq!(
        last_member, "  extra?: Record<string, KitDocValue>;",
        "the extra member must be the final member of the JobFactory interface"
    );

    assert!(
        workflow.contains("export type JobIf = KitExpr<boolean> | boolean;"),
        "job-if must be declared as kit expressions or booleans"
    );
    assert!(
        !schema
            .get("job-if")
            .expect("the workflow schema must define job-if")
            .contexts
            .is_empty(),
        "job-if must declare contexts for the kit-expression assertion above"
    );

    let permission_any = schema
        .get("permission-level-any")
        .expect("the workflow schema must define permission-level-any");
    match &permission_any.kind {
        Kind::OneOf { members } => {
            let names: Vec<&str> = members
                .iter()
                .filter_map(|member| member.as_definition())
                .collect();
            assert_eq!(
                names,
                [
                    "permission-level-read",
                    "permission-level-write",
                    "permission-level-no-access"
                ],
                "permission-level-any must accept the three permission levels in order"
            );
        }
        other => panic!("permission-level-any must be a one-of, found {other:?}"),
    }
    assert!(
        workflow.contains(
            "export type PermissionLevelAny = PermissionLevelRead | PermissionLevelWrite | PermissionLevelNoAccess;"
        ),
        "permission-level-any must be the union of the permission level names in order"
    );

    assert_string_loose_mapping(schema, "job-env");
    assert!(
        workflow.contains("export type JobEnv = Record<string, KitVal<KitScalar>>;"),
        "a loose-string mapping with contexts must render as Record<string, KitVal<KitScalar>>"
    );

    let action = content(&files, "action.ts");
    let action_schema = preloop_gha_schema::action();
    for (definition_name, type_name) in [("step-with", "StepWith"), ("step-env", "StepEnv")] {
        assert_string_loose_mapping(schema, definition_name);
        assert_string_loose_mapping(action_schema, definition_name);
        let expected = format!("export type {type_name} = Record<string, KitVal<KitScalar>>;");
        assert!(
            workflow.contains(expected.as_str()),
            "`{definition_name}` must be declared in workflow.ts as `{expected}`"
        );
        assert!(
            action.contains(expected.as_str()),
            "`{definition_name}` must be declared in action.ts as `{expected}`"
        );
    }

    let string_context = schema
        .get("string-needs-context")
        .expect("the workflow schema must define string-needs-context");
    assert!(
        !string_context.contexts.is_empty(),
        "string-needs-context must declare contexts"
    );
    assert!(
        matches!(&string_context.kind, Kind::String { constant: None, .. }),
        "string-needs-context must be a string definition without a constant"
    );
    assert!(
        workflow.contains("export type StringNeedsContext = KitVal<string>;"),
        "a string-kind definition with contexts must still render as KitVal<string>"
    );
}

#[test]
fn descriptions_render_as_tsdoc_and_escape_terminators() {
    let files = generated_files();
    let workflow = content(&files, "workflow.ts");
    let schema = preloop_gha_schema::workflow();

    let description = schema
        .get("job-env")
        .expect("the workflow schema must define job-env")
        .description
        .as_deref()
        .expect("job-env must carry a description");
    let marker = "export type JobEnv";
    let index = workflow
        .find(marker)
        .unwrap_or_else(|| panic!("missing declaration `{marker}`"));
    let prefix = workflow[..index].trim_end();
    assert!(
        prefix.ends_with("*/"),
        "a described definition must be preceded by a TSDoc block"
    );
    let block_start = prefix
        .rfind("/**")
        .expect("the TSDoc block must open with `/**`");
    assert!(
        prefix[block_start..].contains(description),
        "the TSDoc block must carry the definition description"
    );

    // No description in the vendored schemas contains `*/`, so end-to-end
    // escaping cannot be observed through the generator's public API today.
    // Collect any such descriptions instead: should the schemas gain one, the
    // assertion below proves the emitted text escapes the terminator.
    let mut terminated: Vec<(String, String)> = Vec::new();
    for (schema_name, candidate) in [
        ("workflow", preloop_gha_schema::workflow()),
        ("action", preloop_gha_schema::action()),
    ] {
        for (name, definition) in &candidate.definitions {
            if let Some(text) = definition
                .description
                .as_deref()
                .filter(|text| text.contains("*/"))
            {
                terminated.push((format!("{schema_name}:{name}"), text.to_owned()));
            }
            if let Kind::Mapping { properties, .. } = &definition.kind {
                for (key, property) in properties {
                    if let Some(text) = property
                        .description
                        .as_deref()
                        .filter(|text| text.contains("*/"))
                    {
                        terminated.push((format!("{schema_name}:{name}.{key}"), text.to_owned()));
                    }
                }
            }
        }
    }
    let action = content(&files, "action.ts");
    for (label, text) in terminated {
        for line in text.lines().filter(|line| line.contains("*/")) {
            let escaped = line.replace("*/", "*\\/");
            let escaped = escaped.trim();
            assert!(
                workflow.contains(escaped) || action.contains(escaped),
                "{label}: a `*/` inside a description must be escaped as `*\\/`"
            );
        }
    }
}

