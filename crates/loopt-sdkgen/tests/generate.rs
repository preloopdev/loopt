//! Integration tests for the TypeScript generator.
//!
//! Every test drives only the crate's public API and the schema model the
//! generator reads, so a failure means the emitted TypeScript drifted from the
//! vendored schemas or from the output contract.

use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use loopt_sdkgen::{generate_typescript, stale_files, write_all, GeneratedFile};
use preloop_gha_schema::{BuiltinType, Kind, Schema, TypeRef};

/// The complete set of generated files, relative to the output directory.
const GENERATED_PATHS: [&str; 4] = ["model.ts", "aliases.ts", "workflow.ts", "action.ts"];

/// The prefix of the first header line every generated file carries.
const HEADER_FIRST_PREFIX: &str = "// GENERATED by loopt-sdkgen from ";

/// The second header line every generated file carries.
const HEADER_SECOND: &str = "// Regenerate with: cargo run -p loopt-sdkgen -- typescript";

/// The import line that must open `workflow.ts` and `action.ts`.
const KIT_IMPORT: &str =
    "import type { DocValue as KitDocValue, Expr as KitExpr, Scalar as KitScalar, Val as KitVal } from \"../kit/index.ts\";";

/// Generates the files once for a test.
fn generated_files() -> Vec<GeneratedFile> {
    generate_typescript().expect("the generator must succeed for the embedded schemas")
}

/// Returns the content of one generated file.
fn content<'a>(files: &'a [GeneratedFile], path: &str) -> &'a str {
    files
        .iter()
        .find(|file| file.path == path)
        .map(|file| file.content.as_str())
        .unwrap_or_else(|| panic!("missing generated file `{path}`"))
}

/// Extracts the JSON initialiser of a `export const <name> ... = <json>;`
/// declaration from generated TypeScript.
///
/// The initialiser is located by brace matching rather than by splitting on
/// `;`, because JSON strings may contain semicolons and braces.
fn json_initializer<'a>(content: &'a str, const_name: &str) -> &'a str {
    let marker = format!("export const {const_name}");
    let start = content
        .find(marker.as_str())
        .unwrap_or_else(|| panic!("output has no `{marker}` declaration"));
    let after_name = &content[start + marker.len()..];
    let equals = after_name
        .find('=')
        .unwrap_or_else(|| panic!("`{marker}` declaration has no initialiser"));
    let initialiser = &after_name[equals + 1..];
    let open_offset = initialiser
        .find(['{', '['])
        .unwrap_or_else(|| panic!("`{marker}` initialiser is not a JSON object or array"));
    let open = initialiser.as_bytes()[open_offset];
    let close = if open == b'{' { b'}' } else { b']' };

    let bytes = initialiser.as_bytes();
    let mut depth = 0usize;
    let mut in_string = false;
    let mut escaped = false;
    let mut index = open_offset;
    while index < bytes.len() {
        let byte = bytes[index];
        if in_string {
            if escaped {
                escaped = false;
            } else if byte == b'\\' {
                escaped = true;
            } else if byte == b'"' {
                in_string = false;
            }
        } else if byte == b'"' {
            in_string = true;
        } else if byte == open {
            depth += 1;
        } else if byte == close {
            depth -= 1;
            if depth == 0 {
                let end = index + 1;
                let trailing = initialiser[end..].trim_start();
                assert!(
                    trailing.starts_with(';'),
                    "`{marker}` initialiser must be terminated by `;`"
                );
                return &initialiser[open_offset..end];
            }
        }
        index += 1;
    }
    panic!("`{marker}` initialiser is unterminated");
}

/// Converts an exact schema key into the camelCase spelling used by generated
/// property names and aliases.
fn camel_case(key: &str) -> String {
    let mut out = String::new();
    for (index, word) in key.split(['-', '_']).enumerate() {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            if index == 0 {
                out.extend(first.to_lowercase());
            } else {
                out.extend(first.to_uppercase());
            }
            out.push_str(chars.as_str());
        }
    }
    out
}

/// Converts a definition name into its PascalCase TypeScript name.
fn pascal_case(name: &str) -> String {
    let mut out = String::new();
    for word in name.split(['-', '_']) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

/// Builds the alias table the generator is expected to emit for a schema.
fn expected_aliases(schema: &Schema) -> serde_json::Value {
    let mut definitions = serde_json::Map::new();
    for (name, definition) in &schema.definitions {
        let Kind::Mapping { properties, .. } = &definition.kind else {
            continue;
        };
        if properties.is_empty() {
            continue;
        }
        let mut aliases = serde_json::Map::new();
        for key in properties.keys() {
            aliases.insert(camel_case(key), serde_json::Value::String(key.clone()));
        }
        definitions.insert(name.clone(), serde_json::Value::Object(aliases));
    }
    serde_json::Value::Object(definitions)
}

/// Reads a string member out of a parsed alias table.
fn alias<'a>(table: &'a serde_json::Value, definition: &str, name: &str) -> Option<&'a str> {
    table.get(definition)?.get(name)?.as_str()
}

/// Lists the top-level type declarations in a generated file.
fn declared_names(content: &str) -> Vec<String> {
    let mut names = Vec::new();
    for line in content.lines() {
        for prefix in ["export interface ", "export type "] {
            if let Some(rest) = line.strip_prefix(prefix) {
                let name: String = rest
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '$')
                    .collect();
                assert!(!name.is_empty(), "declaration without a name: `{line}`");
                names.push(name);
            }
        }
    }
    names
}

/// Returns the lines of a declaration starting at `header` up to its closing
/// brace at column zero.
fn declaration_block<'a>(content: &'a str, header: &str) -> &'a str {
    let start = content
        .find(header)
        .unwrap_or_else(|| panic!("missing declaration `{header}`"));
    let rest = &content[start..];
    let end = rest
        .find("\n}")
        .map(|offset| offset + 2)
        .unwrap_or(rest.len());
    &rest[..end]
}

/// Asserts that `name` is a mapping definition without declared properties,
/// with non-empty contexts and the builtin string loose value.
fn assert_string_loose_mapping(schema: &Schema, name: &str) {
    let definition = schema
        .get(name)
        .unwrap_or_else(|| panic!("the schema must define `{name}`"));
    assert!(
        !definition.contexts.is_empty(),
        "`{name}` must declare contexts for the KitScalar assertion"
    );
    let loose_value = match &definition.kind {
        Kind::Mapping {
            properties,
            loose_value: Some(loose_value),
            ..
        } => {
            assert!(
                properties.is_empty(),
                "`{name}` must be a mapping without declared properties"
            );
            loose_value
        }
        other => panic!("`{name}` must be a mapping with a looseValue, found {other:?}"),
    };
    assert_eq!(
        loose_value,
        &TypeRef::Builtin(BuiltinType::String),
        "`{name}` must use the builtin string looseValue for the KitScalar assertion"
    );
}

/// A uniquely named directory under the system temporary directory that
/// removes itself when the test ends.
struct TempDir {
    path: PathBuf,
}

impl TempDir {
    fn new(tag: &str) -> Self {
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("the system clock must be after the Unix epoch")
            .as_nanos();
        let unique = COUNTER.fetch_add(1, Ordering::Relaxed);
        let path = env::temp_dir().join(format!(
            "loopt-sdkgen-test-{tag}-{}-{nanos}-{unique}",
            std::process::id()
        ));
        fs::create_dir_all(&path).expect("creating the temporary directory must succeed");
        Self { path }
    }

    fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

#[test]
fn emits_exactly_four_well_formed_files() {
    let files = generated_files();
    let paths: Vec<&str> = files.iter().map(|file| file.path.as_str()).collect();
    let unique: BTreeSet<&str> = paths.iter().copied().collect();
    assert_eq!(
        unique.len(),
        paths.len(),
        "generated file paths must be unique"
    );

    let expected: BTreeSet<&str> = GENERATED_PATHS.iter().copied().collect();
    assert_eq!(
        unique, expected,
        "the output must contain exactly the four generated files"
    );

    for file in &files {
        let mut lines = file.content.lines();
        let first = lines.next().unwrap_or_default();
        assert!(
            first.starts_with(HEADER_FIRST_PREFIX),
            "{}: the first line must name the generator",
            file.path
        );
        assert!(
            first.ends_with(" - do not edit."),
            "{}: the first line must end with the do-not-edit marker",
            file.path
        );
        assert!(
            first.contains("workflow-v1.0"),
            "{}: the header must name the workflow schema file",
            file.path
        );
        assert!(
            first.contains("action-v1.0"),
            "{}: the header must name the action schema file",
            file.path
        );
        assert_eq!(
            lines.next(),
            Some(HEADER_SECOND),
            "{}: the second line must be the regeneration hint",
            file.path
        );
        assert!(
            file.content.ends_with('\n'),
            "{}: the file must end with a newline",
            file.path
        );
        assert!(
            !file.content.ends_with("\n\n"),
            "{}: the file must end with a single trailing newline",
            file.path
        );
    }
}

