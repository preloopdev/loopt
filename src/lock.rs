struct ParsedLockfile {
    /// spec key -> (ref, sha, owner_id, repo_id)
    deps: BTreeMap<String, (String, String, u64, u64)>,
    /// spec key -> direct transitive keys
    dep_uses: BTreeMap<String, Vec<String>>,
    /// workflow path -> listed keys
    workflows: BTreeMap<String, Vec<String>>,
}

fn parse_lockfile_at(
    root: &Path,
    relative: &str,
    expected_version: &str,
    required: bool,
) -> Result<Option<ParsedLockfile>> {
    let path = Path::new(relative);
    let resolved =
        paths::resolve_within(root, path).with_context(|| format!("resolve {relative}"))?;
    let text = match fs::read_to_string(&resolved) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound && !required => return Ok(None),
        Err(error) if required => {
            return Err(error).with_context(|| format!("read {relative}; run `loopt lock` first"))
        }
        Err(error) => return Err(error).with_context(|| format!("read {relative}")),
    };
    let document = WorkflowDocument::parse(&text)
        .map_err(|error| anyhow::anyhow!("{relative}: invalid YAML: {error}"))?;
    let document_root = document.value();
    let version = document_root
        .get("version")
        .and_then(JsonValue::as_str)
        .with_context(|| format!("{relative}: missing `version`"))?;
    // `gh actions-lock` writes v0.0.3, which only adds an optional `hostname`
    // field to v0.0.2. Accept it so a lockfile written by either tool verifies
    // under the other; entries carrying a `hostname` are rejected below
    // because loopt only resolves against the authenticated host.
    let supported = version == expected_version
        || (expected_version == LOCKFILE_VERSION && version == "v0.0.3");
    if !supported {
        bail!("{relative}: unsupported version {version:?} (expected {expected_version:?})");
    }

    let mut deps = BTreeMap::new();
    let mut dep_uses: BTreeMap<String, Vec<String>> = BTreeMap::new();
    if let Some(deps_map) = document_root
        .get("dependencies")
        .and_then(JsonValue::as_object)
    {
        for (key, entry) in deps_map {
            if let Some(hostname) = entry.get("hostname").and_then(JsonValue::as_str) {
                bail!(
                    "{relative}: {key} is pinned to hostname {hostname:?}; loopt lock only \
                     supports lockfiles for the authenticated host"
                );
            }
            let ref_ = entry
                .get("ref")
                .and_then(JsonValue::as_str)
                .with_context(|| format!("{relative}: {key} missing `ref`"))?
                .to_string();
            let commit = entry
                .get("commit")
                .and_then(JsonValue::as_str)
                .with_context(|| format!("{relative}: {key} missing `commit`"))?;
            let sha = commit
                .strip_prefix("sha1-")
                .with_context(|| format!("{relative}: {key} commit must be sha1-…"))?
                .to_string();
            let owner_id = entry
                .get("owner_id")
                .and_then(JsonValue::as_u64)
                .with_context(|| format!("{relative}: {key} missing `owner_id`"))?;
            let repo_id = entry
                .get("repo_id")
                .and_then(JsonValue::as_u64)
                .with_context(|| format!("{relative}: {key} missing `repo_id`"))?;
            let uses = entry
                .get("uses")
                .and_then(JsonValue::as_array)
                .map(|list| {
                    list.iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default();
            dep_uses.insert(key.clone(), uses);
            deps.insert(key.clone(), (ref_, sha, owner_id, repo_id));
        }
    }

    let mut workflows = BTreeMap::new();
    if let Some(map) = document_root
        .get("workflows")
        .and_then(JsonValue::as_object)
    {
        for (path, list) in map {
            let keys = list
                .as_array()
                .map(|list| {
                    list.iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default();
            workflows.insert(path.clone(), keys);
        }
    }
    Ok(Some(ParsedLockfile {
        deps,
        dep_uses,
        workflows,
    }))
}

/// Collect the workflow paths to scan, following local reusable-workflow
/// calls so a path-scoped run still covers their `uses:`.
fn expand_local_callees(root: &Path, workflows: &[PathBuf]) -> Result<Vec<PathBuf>> {
    let mut queue: VecDeque<PathBuf> = workflows.iter().cloned().collect();
    let mut seen: BTreeSet<PathBuf> = workflows.iter().cloned().collect();
    while let Some(path) = queue.pop_front() {
        let text = fs::read_to_string(root.join(&path))
            .with_context(|| format!("read {}", path.display()))?;
        let document = WorkflowDocument::parse(&text)
            .map_err(|error| anyhow::anyhow!("{}: invalid YAML: {error}", path.display()))?;
        let mut notes = Vec::new();
        for item in workflow_calls(&document, &mut notes, &path.display().to_string()) {
            let Uses::LocalWorkflow(relative) = item else {
                continue;
            };
            let relative = PathBuf::from(relative);
            let exists = paths::resolve_within(root, &relative)
                .map(|resolved| resolved.is_file())
                .unwrap_or(false);
            if exists && seen.insert(relative.clone()) {
                queue.push_back(relative);
            }
        }
    }
    let mut out: Vec<PathBuf> = seen.into_iter().collect();
    out.sort();
    Ok(out)
}

/// Coverage, closure, and stale checks for one lockfile.
fn check_entries(
    file: &str,
    finding_lockfile: Option<&'static str>,
    lock: &ParsedLockfile,
    directs: &BTreeMap<String, Vec<String>>,
    findings: &mut Vec<Finding>,
) {
    let mut seen_keys: BTreeSet<String> = BTreeSet::new();

    for (display, direct) in directs {
        // Coverage: every direct key must be present in dependencies.
        for key in direct {
            seen_keys.insert(key.clone());
            if lock.deps.contains_key(key) {
                continue;
            }
            let (nwo, _) = key
                .rsplit_once('@')
                .map(|(n, r)| (n.to_string(), r.to_string()))
                .unwrap_or_else(|| (key.clone(), String::new()));
            let detail = match lock
                .deps
                .keys()
                .find(|key| key.rsplit_once('@').map(|(n, _)| n) == Some(nwo.as_str()))
            {
                Some(locked_key) => {
                    format!("workflow uses {key:?} but {file} pins {locked_key:?} (ref-changed)")
                }
                None => format!("workflow uses {key:?} but {file} has no entry (missing)"),
            };
            findings.push(Finding {
                severity: "error",
                category: "missing",
                lockfile: finding_lockfile,
                workflow: Some(display.clone()),
                dependency: key.clone(),
                detail,
            });
        }

        // Expected keys for this workflow: direct keys plus the transitive
        // closure reachable via the lockfile's `uses:` lists.
        let mut expected: BTreeSet<String> = direct.iter().cloned().collect();
        let mut stack: Vec<String> = direct.clone();
        while let Some(key) = stack.pop() {
            if let Some(nested) = lock.dep_uses.get(&key) {
                for nested_key in nested {
                    if expected.insert(nested_key.clone()) {
                        stack.push(nested_key.clone());
                    }
                }
            }
        }
        for key in &expected {
            seen_keys.insert(key.clone());
        }

        // Every key reached through a recorded `uses:` edge must have its own
        // entry, or the graph cannot be verified end to end.
        for key in &expected {
            if !direct.contains(key) && !lock.deps.contains_key(key) {
                findings.push(Finding {
                    severity: "error",
                    category: "missing",
                    lockfile: finding_lockfile,
                    workflow: Some(display.clone()),
                    dependency: key.clone(),
                    detail: format!(
                        "{key:?} is referenced through {file}'s uses: graph but has no entry"
                    ),
                });
            }
        }

        match lock.workflows.get(display) {
            Some(listed) => {
                let listed_set: BTreeSet<&String> = listed.iter().collect();
                for key in &expected {
                    if !listed_set.contains(key) {
                        findings.push(Finding {
                            severity: "error",
                            category: "missing",
                            lockfile: finding_lockfile,
                            workflow: Some(display.clone()),
                            dependency: key.clone(),
                            detail: format!(
                                "{key:?} is required by this workflow but absent from its {file} entry"
                            ),
                        });
                    }
                }
            }
            None => findings.push(Finding {
                severity: "error",
                category: "missing",
                lockfile: finding_lockfile,
                workflow: Some(display.clone()),
                dependency: String::new(),
                detail: format!("workflow is absent from {file}'s workflows map"),
            }),
        }
    }

    // Stale: lockfile entries no workflow references.
    for key in lock.deps.keys() {
        if !seen_keys.contains(key) {
            findings.push(Finding {
                severity: "error",
                category: "stale",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!("{file} pins {key:?} but no workflow references it"),
            });
        }
    }
}

/// Online provenance: every pinned ref still resolves to the pinned SHA and
/// the repository ids still match.
fn check_drift(
    root: &Path,
    file: &str,
    finding_lockfile: Option<&'static str>,
    lock: &ParsedLockfile,
    findings: &mut Vec<Finding>,
) {
    for (key, (ref_, sha, owner_id, repo_id)) in &lock.deps {
        let (source, _) = key.rsplit_once('@').unwrap_or((key.as_str(), ""));
        let components: Vec<&str> = source.split('/').collect();
        if components.len() < 2 {
            findings.push(Finding {
                severity: "error",
                category: "invalid",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!("{file}: key is not OWNER/REPO[/PATH]@REF"),
            });
            continue;
        }
        let owner = components[0];
        let repo = components[1];
        match gh::resolve_commit(root, owner, repo, ref_) {
            Ok(actual) if &actual != sha => findings.push(Finding {
                severity: "error",
                category: "moved",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!("{file}: ref {ref_} now resolves to {actual}, lockfile pins {sha}"),
            }),
            Ok(_) => {}
            Err(error) => findings.push(Finding {
                severity: "error",
                category: "unresolvable",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!("{file}: cannot resolve: {error}"),
            }),
        }
        match gh::repo_ids(root, owner, repo) {
            Ok((oid, rid)) if oid != *owner_id || rid != *repo_id => findings.push(Finding {
                severity: "error",
                category: "provenance",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!(
                    "{file}: repository ids changed: lockfile has owner_id={owner_id} repo_id={repo_id}, GitHub reports owner_id={oid} repo_id={rid}"
                ),
            }),
            Ok(_) => {}
            Err(error) => findings.push(Finding {
                severity: "warning",
                category: "unverifiable",
                lockfile: finding_lockfile,
                workflow: None,
                dependency: key.clone(),
                detail: format!("{file}: cannot check repository ids: {error}"),
            }),
        }
    }
}

/// Coverage + drift checks shared by `--verify` and `--verify-local`.
fn verify(root: &Path, workflows: &[PathBuf], online: bool, json: bool) -> Result<()> {
    let workflows = expand_local_callees(root, workflows)?;
    let actions_lock = parse_lockfile_at(root, LOCKFILE_PATH, LOCKFILE_VERSION, true)?
        .expect("required lockfile parses");
    let reusable_lock = parse_lockfile_at(
        root,
        REUSABLE_LOCKFILE_PATH,
        REUSABLE_LOCKFILE_VERSION,
        false,
    )?;

    let mut findings: Vec<Finding> = Vec::new();
    let mut action_directs: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut reusable_directs: BTreeMap<String, Vec<String>> = BTreeMap::new();

    for path in &workflows {
        let display = path.display().to_string().replace('\\', "/");
        let text = fs::read_to_string(root.join(path))
            .with_context(|| format!("read {}", path.display()))?;
        let document = WorkflowDocument::parse(&text)
            .map_err(|error| anyhow::anyhow!("{}: invalid YAML: {error}", path.display()))?;

        let mut notes = Vec::new();
        let mut direct = Vec::new();
        for item in workflow_uses(&document, &mut notes, &display) {
            if let Uses::Remote(spec) = item {
                if !direct.contains(&spec.key) {
                    direct.push(spec.key);
                }
            }
        }
        let mut calls = Vec::new();
        for item in workflow_calls(&document, &mut notes, &display) {
            match item {
                Uses::Reusable(spec) => {
                    if !calls.contains(&spec.key) {
                        calls.push(spec.key);
                    }
                }
                Uses::LocalWorkflow(relative) => {
                    let relative = PathBuf::from(relative);
                    let exists = paths::resolve_within(root, &relative)
                        .map(|resolved| resolved.is_file())
                        .unwrap_or(false);
                    if !exists {
                        notes.push(format!(
                            "{display}: local reusable workflow {} does not exist",
                            relative.display()
                        ));
                    }
                }
                Uses::Local => notes.push(format!(
                    "{display}: a local reusable workflow call is not pinned"
                )),
                Uses::Remote(spec) => notes.push(format!(
                    "{display}: {} is not a reusable workflow call and is not locked",
                    spec.key
                )),
                Uses::Docker => notes.push(format!(
                    "{display}: a docker:// image at jobs.<id>.uses is not locked"
                )),
                Uses::Dynamic => notes.push(format!(
                    "{display}: a jobs.<id>.uses value is dynamic and is not locked"
                )),
            }
        }
        for note in notes {
            eprintln!("note: {note}");
        }

        action_directs.insert(display.clone(), direct);
        if !calls.is_empty() {
            reusable_directs.insert(display, calls);
        }
    }

    check_entries(
        LOCKFILE_PATH,
        None,
        &actions_lock,
        &action_directs,
        &mut findings,
    );
    match &reusable_lock {
        Some(lock) => check_entries(
            REUSABLE_LOCKFILE_PATH,
            Some(REUSABLE_LOCKFILE_PATH),
            lock,
            &reusable_directs,
            &mut findings,
        ),
        None => {
            // An existing actions.lock from before reusable support is fine;
            // the missing reusable pins are reported per call, which is the
            // expected state after an upgrade until `loopt lock` is re-run.
            for (workflow, calls) in &reusable_directs {
                for key in calls {
                    findings.push(Finding {
                        severity: "error",
                        category: "missing",
                        lockfile: Some(REUSABLE_LOCKFILE_PATH),
                        workflow: Some(workflow.clone()),
                        dependency: key.clone(),
                        detail: format!(
                            "workflow calls {key:?} but {REUSABLE_LOCKFILE_PATH} does not exist (missing); run `loopt lock` to create it"
                        ),
                    });
                }
            }
        }
    }

    if online {
        check_drift(root, LOCKFILE_PATH, None, &actions_lock, &mut findings);
        if let Some(lock) = &reusable_lock {
            check_drift(
                root,
                REUSABLE_LOCKFILE_PATH,
                Some(REUSABLE_LOCKFILE_PATH),
                lock,
                &mut findings,
            );
        }
    }

    if json {
        let valid = !findings.iter().any(|finding| finding.severity == "error");
        let out = serde_json::json!({
            "valid": valid,
            "mode": if online { "verify" } else { "verify-local" },
            "findings": findings,
        });
        println!("{}", serde_json::to_string_pretty(&out)?);
    } else {
        for finding in &findings {
            let scope = finding
                .workflow
                .as_deref()
                .map(|workflow| format!("{workflow}: "))
                .unwrap_or_default();
            eprintln!(
                "{}{} [{}] {}",
                scope, finding.severity, finding.category, finding.detail
            );
        }
        if findings.is_empty() {
            let reusable = reusable_lock.as_ref().map_or(0, |lock| lock.deps.len());
            println!(
                "lockfile verified: {} action dependencies and {reusable} reusable-workflow dependencies OK",
                actions_lock.deps.len()
            );
        }
    }

    if findings.iter().any(|finding| finding.severity == "error") {
        bail!("lockfile verification failed; re-run `loopt lock` to refresh");
    }
    Ok(())
}
