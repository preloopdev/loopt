//! `loopt lock`: GitHub workflow dependency lockfile.
//!
//! Generates and verifies `.github/workflows/actions.lock`, the lockfile
//! format consumed by GitHub's `gh-actions-lock` extension and enforced by
//! the hosted runner (lockfile version `v0.0.2`). Every remote step-level
//! `uses:` in the repository's workflows is pinned to the commit SHA it
//! resolves to, together with the repository's numeric `owner_id`/`repo_id`.
//!
//! Reusable-workflow calls (`jobs.<id>.uses`) are pinned separately, in
//! `.github/workflows/reusable.lock` (loopt's own `v0.0.1` format). GitHub's
//! schema cannot carry them: `actions.lock` rejects unknown top-level keys
//! and unknown action fields, its pin grammar is `OWNER/REPO@REF` with no
//! workflow path, and GitHub's documentation states the lockfile "doesn't
//! pin calls to reusable workflows" and that a reusable workflow's
//! dependencies are covered by the lockfile of the repository that defines
//! it. Upstream deliberately keeps them out too
//! (<https://github.com/github/gh-actions-lock/issues/179>). Keeping them in
//! a sibling file leaves `actions.lock` byte-for-byte compatible with
//! `gh actions-lock`, which never reads the sibling.
//!
//! Scope:
//!   - step-level `uses:` of remote actions are locked in `actions.lock`;
//!   - composite actions contribute their own `uses:` steps transitively;
//!   - remote reusable-workflow calls are locked in `reusable.lock` with the
//!     same entry shape, and the callee workflow is fetched at the pinned
//!     SHA so its own step `uses:` and nested calls are locked transitively;
//!   - local `./…` callees are not pin-able themselves, but their files are
//!     read so their `uses:` are locked too;
//!   - local `./…` actions, `$/…` specifiers, `docker://` images, and
//!     `${{ }}` expressions are not lockable and are reported as notes.
//!
//! Modes:
//!   `loopt lock`                resolve everything and (re)write the lockfiles
//!   `loopt lock --verify`       coverage plus ref/provenance drift (network)
//!   `loopt lock --verify-local` offline coverage: every uses: has an entry
//!
//! `loopt lock` and GitHub's `gh actions-lock` operate on the same
//! `actions.lock`; a lockfile written by either tool verifies under the other.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use preloop_gha_authoring::WorkflowDocument;
use serde::Serialize;
use serde_json::Value as JsonValue;

use crate::gh;
use crate::paths;

const WORKFLOWS_DIR: &str = ".github/workflows";
const LOCKFILE_PATH: &str = ".github/workflows/actions.lock";
const LOCKFILE_VERSION: &str = "v0.0.2";
/// Reusable-workflow pins live in a loopt-owned sibling file. GitHub's
/// `actions.lock` schema (`additionalProperties: false`) and its
/// `OWNER/REPO@REF` pin grammar cannot represent a workflow file, and the
/// hosted runner does not enforce reusable calls, so keeping them out of
/// `actions.lock` preserves compatibility with `gh actions-lock` and the
/// runner. See the module docs.
const REUSABLE_LOCKFILE_PATH: &str = ".github/workflows/reusable.lock";
const REUSABLE_LOCKFILE_VERSION: &str = "v0.0.1";
const REUSABLE_LOCKFILE_HEADER: &str = "# This file is machine-generated by `loopt lock`.\n\
# Do not edit by hand; run `loopt lock` to update.\n\
# Reusable-workflow pins only. GitHub Actions and `gh actions-lock` do not read\n\
# this file; they read the sibling actions.lock.\n";

/// One remote `uses:` target: `owner/repo[/subpath]@ref`.
#[derive(Debug, Clone)]
struct UsesSpec {
    /// Canonical key exactly as written in the workflow.
    key: String,
    owner: String,
    repo: String,
    /// Repository-relative directory containing `action.yml`; "" for root.
    subpath: String,
    ref_: String,
}

/// One remote reusable-workflow call:
/// `owner/repo/.github/workflows/<file>@ref`.
#[derive(Debug, Clone)]
struct ReusableSpec {
    /// Canonical key exactly as written in the workflow; includes the
    /// workflow path, so two callees in one repository never collide.
    key: String,
    owner: String,
    repo: String,
    /// Repository-relative workflow path, e.g. `.github/workflows/lint.yml`.
    path: String,
    ref_: String,
}

/// Classification of a `uses:` value for locking.
enum Uses {
    /// `owner/repo[/subpath]@ref` — lockable.
    Remote(UsesSpec),
    /// `owner/repo/.github/workflows/<file>@ref` — a reusable-workflow call,
    /// lockable in `reusable.lock`.
    Reusable(ReusableSpec),
    /// `./…`, `/…`, `$/…` — same-repository content, not lockable by commit.
    /// At `jobs.<id>.uses` the payload is the callee's repository-relative
    /// path so the file can be read from disk.
    Local,
    /// `jobs.<id>.uses: ./…` — a local reusable-workflow call. The path is
    /// repository-relative (no `./` or `$/` prefix).
    LocalWorkflow(String),
    /// `docker://…` — container images are out of scope for the lockfile.
    Docker,
    /// `uses:` containing a `${{ }}` expression or otherwise unclassifiable —
    /// not statically lockable.
    Dynamic,
}

/// One resolved `dependencies` entry.
#[derive(Debug)]
struct LockedDep {
    ref_: String,
    sha: String,
    owner_id: u64,
    repo_id: u64,
    /// Direct transitive `uses:` keys declared inside a composite action.
    uses: Vec<String>,
}

/// Everything resolved for one lock run.
struct ResolvedWork {
    /// workflow path -> ordered spec keys (direct first, then transitives)
    workflows: Vec<(PathBuf, Vec<String>)>,
    deps: BTreeMap<String, LockedDep>,
    /// workflow path -> ordered reusable-call keys, for `reusable.lock`.
    reusable_workflows: Vec<(PathBuf, Vec<String>)>,
    /// Reusable calls and the `uses:` inside their callees.
    reusable_deps: BTreeMap<String, LockedDep>,
    /// Human-readable notes about skipped/unlockable `uses:` values.
    notes: Vec<String>,
}

/// Which lockfile a resolved action entry belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Sink {
    /// Step-level `uses:` in this repository's workflows -> `actions.lock`.
    Actions,
    /// `uses:` inside a remote reusable workflow -> `reusable.lock`.
    Reusable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mode {
    /// Resolve everything and (re)write the lockfile.
    Write,
    /// Network verification: coverage plus ref/provenance drift.
    Verify,
    /// Offline coverage: every `uses:` has a matching lockfile entry.
    VerifyLocal,
}

#[derive(Debug, Serialize)]
struct Finding {
    severity: &'static str,
    category: &'static str,
    /// Lockfile the finding refers to; omitted for `actions.lock` findings
    /// so existing JSON consumers keep their shape.
    #[serde(skip_serializing_if = "Option::is_none")]
    lockfile: Option<&'static str>,
    #[serde(skip_serializing_if = "Option::is_none")]
    workflow: Option<String>,
    dependency: String,
    detail: String,
}

pub fn run(root: &Path, args: &[String]) -> Result<()> {
    let (mode, json, paths_arg) = parse_args(args)?;
    let workflows = discover_workflows(root, &paths_arg)?;
    match mode {
        Mode::Write => {
            let work = resolve_all(root, &workflows)?;
            for note in &work.notes {
                eprintln!("note: {note}");
            }
            let text = render_lockfile(LOCKFILE_VERSION, "", &work.workflows, &work.deps);
            paths::write_atomic(root, Path::new(LOCKFILE_PATH), text.as_bytes())
                .context("write .github/workflows/actions.lock")?;

            // Only create the reusable lockfile when there is something to
            // pin (or a previous run left one behind that must be refreshed
            // or emptied), so repositories without reusable calls do not grow
            // a second file.
            let reusable_existing = root.join(REUSABLE_LOCKFILE_PATH).is_file();
            if !work.reusable_deps.is_empty() || reusable_existing {
                let text = render_lockfile(
                    REUSABLE_LOCKFILE_VERSION,
                    REUSABLE_LOCKFILE_HEADER,
                    &work.reusable_workflows,
                    &work.reusable_deps,
                );
                paths::write_atomic(root, Path::new(REUSABLE_LOCKFILE_PATH), text.as_bytes())
                    .context("write .github/workflows/reusable.lock")?;
            }
            println!(
                "locked {} action dependencies and {} reusable-workflow dependencies across {} workflow(s) -> {LOCKFILE_PATH}",
                work.deps.len(),
                work.reusable_deps.len(),
                work.workflows.len()
            );
            Ok(())
        }
        Mode::Verify => verify(root, &workflows, true, json),
        Mode::VerifyLocal => verify(root, &workflows, false, json),
    }
}

fn parse_args(args: &[String]) -> Result<(Mode, bool, Vec<PathBuf>)> {
    let mut mode = Mode::Write;
    let mut json = false;
    let mut paths = Vec::new();
    for arg in args {
        let (flag, inline) = match arg.split_once('=') {
            Some((name, value)) if name.starts_with('-') => (name, Some(value)),
            _ => (arg.as_str(), None),
        };
        match flag {
            "--verify" => {
                if inline.is_some() {
                    bail!("--verify does not take a value");
                }
                if mode != Mode::Write {
                    bail!("--verify cannot be combined with --verify-local");
                }
                mode = Mode::Verify;
            }
            "--verify-local" => {
                if inline.is_some() {
                    bail!("--verify-local does not take a value");
                }
                if mode != Mode::Write {
                    bail!("--verify-local cannot be combined with --verify");
                }
                mode = Mode::VerifyLocal;
            }
            "--json" => {
                if inline.is_some() {
                    bail!("--json does not take a value");
                }
                json = true;
            }
            "-h" | "--help" => {
                print_usage();
                std::process::exit(0);
            }
            _ if flag.starts_with('-') => bail!("unknown lock option {flag:?}"),
            _ => paths.push(PathBuf::from(arg)),
        }
    }
    Ok((mode, json, paths))
}

fn print_usage() {
    eprintln!(
        "usage: loopt lock [--verify|--verify-local] [--json] [WORKFLOW ...]\n\n\
         Generates (default) or verifies .github/workflows/actions.lock, the\n\
         GitHub workflow dependency lockfile enforced by the hosted runner,\n\
         plus .github/workflows/reusable.lock for reusable-workflow calls.\n\
         --verify        resolve every pinned ref over the network, fail on drift\n\
         --verify-local  offline coverage check: every uses: has a lockfile entry\n\
         [WORKFLOW ...]  limit the run to specific workflow paths"
    );
}

fn discover_workflows(root: &Path, explicit: &[PathBuf]) -> Result<Vec<PathBuf>> {
    if !explicit.is_empty() {
        let mut found = Vec::new();
        for path in explicit {
            let relative = paths::relativize(root, path)?;
            paths::resolve_within(root, &relative)
                .with_context(|| format!("{}: unsafe path", relative.display()))?;
            if !root.join(&relative).is_file() {
                bail!("{}: no such file", relative.display());
            }
            found.push(relative);
        }
        found.sort();
        found.dedup();
        return Ok(found);
    }

    let dir = root.join(WORKFLOWS_DIR);
    let mut found = Vec::new();
    if dir.is_dir() {
        for entry in fs::read_dir(&dir).with_context(|| format!("read {}", dir.display()))? {
            let entry = entry.with_context(|| format!("read {}", dir.display()))?;
            if !entry.file_type()?.is_file() {
                continue;
            }
            let path = entry.path();
            if matches!(
                path.extension().and_then(|ext| ext.to_str()),
                Some("yml" | "yaml")
            ) {
                found.push(
                    path.strip_prefix(root)
                        .expect("workflow path is under root")
                        .to_path_buf(),
                );
            }
        }
    }
    found.sort();
    Ok(found)
}

fn valid_component(component: &str) -> bool {
    !component.is_empty()
        && component != "."
        && component != ".."
        && component
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_' | '.'))
}

fn classify_uses(value: &str) -> Result<Uses> {
    let trimmed = value.trim();
    if trimmed.contains("${{") {
        return Ok(Uses::Dynamic);
    }
    if trimmed.starts_with("./")
        || trimmed.starts_with('/')
        || trimmed.starts_with("$/")
        || trimmed == "."
    {
        return Ok(Uses::Local);
    }
    if trimmed.starts_with("docker://") {
        return Ok(Uses::Docker);
    }
    let (source, requested_ref) = trimmed
        .rsplit_once('@')
        .with_context(|| format!("uses: {trimmed:?} has no @ref and cannot be locked"))?;
    let components: Vec<&str> = source.split('/').collect();
    if components.len() < 2
        || components
            .iter()
            .any(|component| !valid_component(component))
    {
        bail!("invalid action source {source:?} in uses:");
    }
    gh::validate_ref(requested_ref)?;
    Ok(Uses::Remote(UsesSpec {
        key: trimmed.to_string(),
        owner: components[0].to_string(),
        repo: components[1].to_string(),
        subpath: components[2..].join("/"),
        ref_: requested_ref.to_string(),
    }))
}

/// Strip a local reference's prefix, returning a repository-relative path.
fn local_relative(value: &str) -> Option<String> {
    let trimmed = value.trim();
    let rest = trimmed
        .strip_prefix("./")
        .or_else(|| trimmed.strip_prefix("$/"))?;
    if rest.is_empty() {
        return None;
    }
    Some(rest.to_string())
}

/// Classify a `jobs.<id>.uses:` value. Remote reusable workflows are
/// lockable; local ones are followed from disk but not pinned.
fn classify_call(value: &str) -> Result<Uses> {
    let trimmed = value.trim();
    if trimmed.contains("${{") {
        return Ok(Uses::Dynamic);
    }
    if let Some(path) = local_relative(trimmed) {
        return Ok(Uses::LocalWorkflow(path));
    }
    if trimmed == "." || trimmed.starts_with('/') {
        return Ok(Uses::Local);
    }
    if trimmed.starts_with("docker://") {
        return Ok(Uses::Docker);
    }
    let (source, requested_ref) = trimmed
        .rsplit_once('@')
        .with_context(|| format!("jobs.<id>.uses: {trimmed:?} has no @ref and cannot be locked"))?;
    let components: Vec<&str> = source.split('/').collect();
    if components.len() != 5
        || components
            .iter()
            .any(|component| !valid_component(component))
        || components[2] != ".github"
        || components[3] != "workflows"
        || !matches!(
            components[4].rsplit_once('.'),
            Some((stem, "yml" | "yaml")) if !stem.is_empty()
        )
    {
        bail!(
            "invalid reusable-workflow call {trimmed:?}; expected \
             owner/repo/.github/workflows/<file>.yml@ref"
        );
    }
    gh::validate_ref(requested_ref)?;
    Ok(Uses::Reusable(ReusableSpec {
        key: trimmed.to_string(),
        owner: components[0].to_string(),
        repo: components[1].to_string(),
        path: components[2..].join("/"),
        ref_: requested_ref.to_string(),
    }))
}

/// Collect step-level `uses:` values from one workflow document, in file
/// order. Only these are lockable in `actions.lock`.
fn workflow_uses(document: &WorkflowDocument, notes: &mut Vec<String>, context: &str) -> Vec<Uses> {
    let mut out = Vec::new();
    let Some(jobs) = document.value().get("jobs").and_then(JsonValue::as_object) else {
        return out;
    };
    for (job_id, job) in jobs {
        let Some(steps) = job.get("steps").and_then(JsonValue::as_array) else {
            // jobs.<id>.uses (reusable workflow calls) are collected by
            // workflow_calls and locked in reusable.lock.
            continue;
        };
        for step in steps {
            let Some(uses) = step.get("uses").and_then(JsonValue::as_str) else {
                continue;
            };
            match classify_uses(uses) {
                Ok(classified) => out.push(classified),
                Err(error) => {
                    // An unclassifiable `uses:` line cannot be locked; report
                    // it and treat the value as unresolvable for coverage so
                    // --verify-local still flags the gap via its key absent.
                    notes.push(format!("{context}: job {job_id:?}: {error}"));
                }
            }
        }
    }
    out
}

/// Collect `jobs.<id>.uses:` reusable-workflow calls, in file order.
fn workflow_calls(
    document: &WorkflowDocument,
    notes: &mut Vec<String>,
    context: &str,
) -> Vec<Uses> {
    let mut out = Vec::new();
    let Some(jobs) = document.value().get("jobs").and_then(JsonValue::as_object) else {
        return out;
    };
    for (job_id, job) in jobs {
        let Some(uses) = job.get("uses").and_then(JsonValue::as_str) else {
            continue;
        };
        match classify_call(uses) {
            Ok(classified) => out.push(classified),
            Err(error) => notes.push(format!("{context}: job {job_id:?}: {error}")),
        }
    }
    out
}

/// Extract remote `uses:` declared inside a composite action's `runs.steps`.
fn composite_uses(metadata_bytes: &[u8], context: &str) -> Result<Vec<Uses>> {
    let source = String::from_utf8(metadata_bytes.to_vec())
        .with_context(|| format!("{context}: not valid UTF-8"))?;
    let document = WorkflowDocument::parse(&source)
        .map_err(|error| anyhow::anyhow!("{context}: invalid YAML: {error}"))?;
    let root = document.value();
    let Some(runs) = root.get("runs").and_then(JsonValue::as_object) else {
        return Ok(Vec::new());
    };
    if runs.get("using").and_then(JsonValue::as_str) != Some("composite") {
        return Ok(Vec::new());
    }
    let mut out = Vec::new();
    if let Some(steps) = runs.get("steps").and_then(JsonValue::as_array) {
        for step in steps {
            if let Some(uses) = step.get("uses").and_then(JsonValue::as_str) {
                match classify_uses(uses) {
                    Ok(classified) => out.push(classified),
                    Err(error) => return Err(error.context(format!("{context}: invalid uses"))),
                }
            }
        }
    }
    Ok(out)
}

struct Resolver<'a> {
    root: &'a Path,
    /// Step-level action pins for this repository -> `actions.lock`.
    actions: BTreeMap<String, LockedDep>,
    /// Reusable calls and the actions their callees use -> `reusable.lock`.
    reusable: BTreeMap<String, LockedDep>,
    /// "owner/repo" -> (owner_id, repo_id)
    ids: BTreeMap<String, (u64, u64)>,
    /// Action spec keys already resolved per sink, for cycle safety.
    seen_actions: BTreeSet<String>,
    seen_reusable_actions: BTreeSet<String>,
    /// Reusable-call keys already resolved (in-flight or done).
    seen_reusable: BTreeSet<String>,
    /// Human-readable notes about skipped/unlockable `uses:` values.
    notes: Vec<String>,
}

impl<'a> Resolver<'a> {
    fn new(root: &'a Path) -> Self {
        Self {
            root,
            actions: BTreeMap::new(),
            reusable: BTreeMap::new(),
            ids: BTreeMap::new(),
            seen_actions: BTreeSet::new(),
            seen_reusable_actions: BTreeSet::new(),
            seen_reusable: BTreeSet::new(),
            notes: Vec::new(),
        }
    }

    fn repo_ids(&mut self, owner: &str, repo: &str) -> Result<(u64, u64)> {
        let key = format!("{owner}/{repo}");
        if let Some(ids) = self.ids.get(&key) {
            return Ok(*ids);
        }
        let ids = gh::repo_ids(self.root, owner, repo)?;
        self.ids.insert(key, ids);
        Ok(ids)
    }

    fn action_seen(&mut self, sink: Sink) -> &mut BTreeSet<String> {
        match sink {
            Sink::Actions => &mut self.seen_actions,
            Sink::Reusable => &mut self.seen_reusable_actions,
        }
    }

    fn action_deps(&mut self, sink: Sink) -> &mut BTreeMap<String, LockedDep> {
        match sink {
            Sink::Actions => &mut self.actions,
            Sink::Reusable => &mut self.reusable,
        }
    }

    /// Resolve one action spec plus its transitive composite dependencies
    /// into the lockfile selected by `sink`.
    fn resolve_action(&mut self, spec: &UsesSpec, sink: Sink) -> Result<()> {
        if !self.action_seen(sink).insert(spec.key.clone()) {
            return Ok(());
        }
        let sha = gh::resolve_commit(self.root, &spec.owner, &spec.repo, &spec.ref_)?;
        let (owner_id, repo_id) = self.repo_ids(&spec.owner, &spec.repo)?;

        // Composite actions may themselves `uses:` remote actions; pull the
        // metadata at the pinned sha and recurse (`seen` guards cycles).
        let base = if spec.subpath.is_empty() {
            String::new()
        } else {
            format!("{}/", spec.subpath)
        };
        let mut transitives = Vec::new();
        let mut failures = Vec::new();
        let mut fetched = false;
        for metadata_file in ["action.yml", "action.yaml"] {
            let path = format!("{base}{metadata_file}");
            match gh::fetch_file(self.root, &spec.owner, &spec.repo, &path, &sha) {
                Ok(bytes) => {
                    fetched = true;
                    transitives = composite_uses(&bytes, &spec.key)?;
                    break;
                }
                Err(error) => failures.push(format!("{metadata_file}: {error}")),
            }
        }
        if !fetched {
            bail!(
                "could not retrieve action metadata for {}@{}:\n- {}",
                spec.key,
                sha,
                failures.join("\n- ")
            );
        }

        let mut uses_keys = Vec::new();
        for item in transitives {
            match item {
                Uses::Remote(child) => {
                    if !uses_keys.contains(&child.key) {
                        uses_keys.push(child.key.clone());
                    }
                    self.resolve_action(&child, sink)?;
                }
                Uses::Reusable(child) => {
                    // A reusable workflow cannot appear in a composite step;
                    // classify_uses never produces this, but keep the match
                    // total without pretending it is lockable here.
                    self.notes.push(format!(
                        "{}: reusable workflow call {} inside a composite is not locked",
                        spec.key, child.key
                    ));
                }
                Uses::Local | Uses::LocalWorkflow(_) => self.notes.push(format!(
                    "{}: local ./ action inside a composite is not locked",
                    spec.key
                )),
                Uses::Docker => self.notes.push(format!(
                    "{}: docker:// image inside a composite is not locked",
                    spec.key
                )),
                Uses::Dynamic => self.notes.push(format!(
                    "{}: composite step uses a ${{ }} expression and cannot be locked",
                    spec.key
                )),
            }
        }

        self.action_deps(sink).insert(
            spec.key.clone(),
            LockedDep {
                ref_: spec.ref_.clone(),
                sha,
                owner_id,
                repo_id,
                uses: uses_keys,
            },
        );
        Ok(())
    }

    /// Resolve one remote reusable-workflow call, its callee's step `uses:`
    /// and the callee's own nested reusable calls, transitively.
    fn resolve_reusable(&mut self, spec: &ReusableSpec) -> Result<()> {
        if !self.seen_reusable.insert(spec.key.clone()) {
            return Ok(());
        }
        let sha = gh::resolve_commit(self.root, &spec.owner, &spec.repo, &spec.ref_)?;
        let (owner_id, repo_id) = self.repo_ids(&spec.owner, &spec.repo)?;
        let bytes = gh::fetch_file(self.root, &spec.owner, &spec.repo, &spec.path, &sha)
            .with_context(|| format!("read reusable workflow {}@{sha}", spec.key))?;
        let source =
            String::from_utf8(bytes).with_context(|| format!("{}: not valid UTF-8", spec.key))?;
        let document = WorkflowDocument::parse(&source)
            .map_err(|error| anyhow::anyhow!("{}: invalid YAML: {error}", spec.key))?;

        let mut uses_keys = Vec::new();

        // Actions used by the callee's own steps are pinned in the same
        // loopt-owned file: GitHub's actions.lock deliberately does not
        // cover a callee's dependencies.
        for item in workflow_uses(&document, &mut self.notes, &spec.key) {
            match item {
                Uses::Remote(child) => {
                    if !uses_keys.contains(&child.key) {
                        uses_keys.push(child.key.clone());
                    }
                    self.resolve_action(&child, Sink::Reusable)?;
                }
                Uses::Reusable(child) => self.notes.push(format!(
                    "{}: reusable workflow call {} in a step is not locked",
                    spec.key, child.key
                )),
                Uses::Local | Uses::LocalWorkflow(_) => self.notes.push(format!(
                    "{}: local ./ reference inside a remote reusable workflow is not locked",
                    spec.key
                )),
                Uses::Docker => self.notes.push(format!(
                    "{}: docker:// image inside a reusable workflow is not locked",
                    spec.key
                )),
                Uses::Dynamic => self.notes.push(format!(
                    "{}: a step uses: value inside a reusable workflow is dynamic and is not locked",
                    spec.key
                )),
            }
        }

        for item in workflow_calls(&document, &mut self.notes, &spec.key) {
            match item {
                Uses::Reusable(child) => {
                    if !uses_keys.contains(&child.key) {
                        uses_keys.push(child.key.clone());
                    }
                    self.resolve_reusable(&child)?;
                }
                Uses::LocalWorkflow(path) => self.notes.push(format!(
                    "{}: local reusable call {path:?} inside a remote workflow is not locked",
                    spec.key
                )),
                Uses::Local => self.notes.push(format!(
                    "{}: local reusable call inside a remote workflow is not locked",
                    spec.key
                )),
                Uses::Remote(child) => self.notes.push(format!(
                    "{}: {} is not a reusable workflow call and is not locked",
                    spec.key, child.key
                )),
                Uses::Docker => self.notes.push(format!(
                    "{}: docker:// image at jobs.<id>.uses is not locked",
                    spec.key
                )),
                Uses::Dynamic => self.notes.push(format!(
                    "{}: a jobs.<id>.uses value inside a reusable workflow is dynamic and is not locked",
                    spec.key
                )),
            }
        }

        self.reusable.insert(
            spec.key.clone(),
            LockedDep {
                ref_: spec.ref_.clone(),
                sha,
                owner_id,
                repo_id,
                uses: uses_keys,
            },
        );
        Ok(())
    }
}

/// Direct keys plus everything reachable through composite `uses:` lists.
fn closure(direct: &[String], deps: &BTreeMap<String, LockedDep>) -> Vec<String> {
    let mut out = Vec::new();
    let mut seen = BTreeSet::new();
    // BFS keeps direct uses: in file order, then transitives breadth-first —
    // the same ordering gh-actions-lock emits in its workflows map.
    let mut queue: VecDeque<String> = direct.iter().cloned().collect();
    while let Some(key) = queue.pop_front() {
        if !seen.insert(key.clone()) {
            continue;
        }
        out.push(key.clone());
        if let Some(dep) = deps.get(&key) {
            for nested in &dep.uses {
                queue.push_back(nested.clone());
            }
        }
    }
    out
}

/// Resolve every remote `uses:` across the given workflows.
///
/// Local reusable-workflow callees are read too, even when the run was
/// limited to specific workflow paths: their step `uses:` and nested calls
/// must be covered as well.
fn resolve_all(root: &Path, workflows: &[PathBuf]) -> Result<ResolvedWork> {
    let mut resolver = Resolver::new(root);
    let mut workflows_out: Vec<(PathBuf, Vec<String>)> = Vec::new();
    let mut reusable_out: Vec<(PathBuf, Vec<String>)> = Vec::new();
    let mut queue: VecDeque<PathBuf> = workflows.iter().cloned().collect();
    let mut queued: BTreeSet<PathBuf> = workflows.iter().cloned().collect();

    while let Some(path) = queue.pop_front() {
        let text = fs::read_to_string(root.join(&path))
            .with_context(|| format!("read {}", path.display()))?;
        let document = WorkflowDocument::parse(&text)
            .map_err(|error| anyhow::anyhow!("{}: invalid YAML: {error}", path.display()))?;
        let context = path.display().to_string();

        let mut direct = Vec::new();
        for item in workflow_uses(&document, &mut resolver.notes, &context) {
            match item {
                Uses::Remote(spec) => {
                    resolver.resolve_action(&spec, Sink::Actions)?;
                    if !direct.contains(&spec.key) {
                        direct.push(spec.key);
                    }
                }
                Uses::Reusable(spec) => resolver.notes.push(format!(
                    "{context}: reusable workflow {} in a step is not locked",
                    spec.key
                )),
                Uses::Local | Uses::LocalWorkflow(_) => resolver
                    .notes
                    .push(format!("{context}: local action reference is not locked")),
                Uses::Docker => resolver
                    .notes
                    .push(format!("{context}: docker:// image is not locked")),
                Uses::Dynamic => resolver.notes.push(format!(
                    "{context}: a uses: value is dynamic or unpinnable and is not locked"
                )),
            }
        }

        let mut calls = Vec::new();
        for item in workflow_calls(&document, &mut resolver.notes, &context) {
            match item {
                Uses::Reusable(spec) => {
                    resolver.resolve_reusable(&spec)?;
                    if !calls.contains(&spec.key) {
                        calls.push(spec.key);
                    }
                }
                Uses::LocalWorkflow(relative) => {
                    let relative = PathBuf::from(relative);
                    match paths::resolve_within(root, &relative) {
                        Ok(resolved) if resolved.is_file() => {
                            if queued.insert(relative.clone()) {
                                queue.push_back(relative);
                            }
                        }
                        Ok(_) => resolver.notes.push(format!(
                            "{context}: local reusable workflow {} does not exist and its uses: cannot be locked",
                            relative.display()
                        )),
                        Err(error) => resolver.notes.push(format!(
                            "{context}: local reusable workflow {} is unsafe: {error}",
                            relative.display()
                        )),
                    }
                }
                Uses::Local => resolver.notes.push(format!(
                    "{context}: a local reusable workflow call is not pinned"
                )),
                Uses::Remote(spec) => resolver.notes.push(format!(
                    "{context}: {} is not a reusable workflow call and is not locked",
                    spec.key
                )),
                Uses::Docker => resolver.notes.push(format!(
                    "{context}: a docker:// image at jobs.<id>.uses is not locked"
                )),
                Uses::Dynamic => resolver.notes.push(format!(
                    "{context}: a jobs.<id>.uses value is dynamic and is not locked"
                )),
            }
        }

        workflows_out.push((path.clone(), direct));
        if !calls.is_empty() {
            reusable_out.push((path, calls));
        }
    }

    workflows_out.sort_by(|left, right| left.0.cmp(&right.0));
    reusable_out.sort_by(|left, right| left.0.cmp(&right.0));

    // Expand each workflow's direct keys to the full transitive closure.
    let workflows = workflows_out
        .into_iter()
        .map(|(path, direct)| (path, closure(&direct, &resolver.actions)))
        .collect();
    let reusable_workflows = reusable_out
        .into_iter()
        .map(|(path, direct)| (path, closure(&direct, &resolver.reusable)))
        .collect();
    Ok(ResolvedWork {
        workflows,
        deps: resolver.actions,
        reusable_workflows,
        reusable_deps: resolver.reusable,
        notes: resolver.notes,
    })
}

fn yaml_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

fn render_lockfile(
    version: &str,
    header: &str,
    workflows: &[(PathBuf, Vec<String>)],
    deps: &BTreeMap<String, LockedDep>,
) -> String {
    let mut out = String::from(header);
    let _ = writeln!(out, "version: '{version}'");
    if deps.is_empty() {
        let _ = writeln!(out, "dependencies: {{}}");
    } else {
        let _ = writeln!(out, "dependencies:");
        for (key, dep) in deps {
            let _ = writeln!(out, "  {}:", yaml_quote(key));
            let _ = writeln!(out, "    ref: {}", yaml_quote(&dep.ref_));
            let _ = writeln!(out, "    commit: 'sha1-{}'", dep.sha);
            let _ = writeln!(out, "    owner_id: {}", dep.owner_id);
            let _ = writeln!(out, "    repo_id: {}", dep.repo_id);
            if !dep.uses.is_empty() {
                let _ = writeln!(out, "    uses:");
                for nested in &dep.uses {
                    let _ = writeln!(out, "      - {}", yaml_quote(nested));
                }
            }
        }
    }
    if workflows.is_empty() {
        let _ = writeln!(out, "workflows: {{}}");
    } else {
        let _ = writeln!(out, "workflows:");
        for (path, keys) in workflows {
            let display = path.display().to_string().replace('\\', "/");
            let _ = writeln!(out, "  {}:", yaml_quote(&display));
            for key in keys {
                let _ = writeln!(out, "    - {}", yaml_quote(key));
            }
        }
    }
    out
}

