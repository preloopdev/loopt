//! Go language integration: emits an editable Go program from a workflow
//! document, and describes how to run it to recover that document.
//!
//! The generated program never smuggles the workflow through as an opaque
//! JSON or YAML string. It rebuilds the document as native Go values —
//! strings, bools, numbers, slices, and a small ordered-object helper for
//! maps — so a user can edit it like any other Go program: add a step with
//! a loop, branch on an environment variable, factor shared values into a
//! helper function, and so on.
//!
//! Go's built-in `encoding/json` package marshals `map[string]interface{}`
//! keys in sorted order, which would silently reorder a workflow's
//! top-level keys, a job's fields, or a matrix's axes. To preserve the
//! exact key order carried in `workflow`, the generated file defines a
//! minimal ordered-object type (`om`, built with `newOM`/`f`) with its own
//! `MarshalJSON`, and uses it for every JSON object instead of a plain Go
//! map.

use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde_json::{Map, Number, Value};

use crate::languages::{CommandSpec, GeneratedFile, GeneratedSource};

const HEADER: &str = "\
// Code generated by `loopt import`. This file is yours to edit: fields
// below are ordinary Go values (strings, bools, numbers, slices, and the
// small ordered-object helper om/f), so add a step with a loop, read an
// environment variable to pick a runner, or pull shared values into a
// function -- anything a normal Go program can do. Run `loopt gen` to
// turn the result back into a workflow YAML file.
package main

import (
\t\"encoding/json\"
\t\"fmt\"
\t\"os\"
)

";

const RUNTIME: &str = "
// omField is one ordered key/value pair of an object.
type omField struct {
\tKey   string
\tValue interface{}
}

// f builds one ordered field for newOM.
func f(key string, value interface{}) omField {
\treturn omField{Key: key, Value: value}
}

// om is an insertion-ordered JSON object. Go's map[string]interface{}
// marshals keys alphabetically, which would reorder workflow keys (and
// matrix axes); om keeps the order fields were added in.
type om struct {
\tfields []omField
}

// newOM builds an ordered object from fields, in the order given.
func newOM(fields ...omField) *om {
\treturn &om{fields: fields}
}

// MarshalJSON writes fields in insertion order instead of Go's default
// alphabetical map ordering.
func (o *om) MarshalJSON() ([]byte, error) {
\tif o == nil || len(o.fields) == 0 {
\t\treturn []byte(\"{}\"), nil
\t}
\tbuf := []byte{'{'}
\tfor i, field := range o.fields {
\t\tif i > 0 {
\t\t\tbuf = append(buf, ',')
\t\t}
\t\tkey, err := json.Marshal(field.Key)
\t\tif err != nil {
\t\t\treturn nil, err
\t\t}
\t\tbuf = append(buf, key...)
\t\tbuf = append(buf, ':')
\t\tval, err := json.Marshal(field.Value)
\t\tif err != nil {
\t\t\treturn nil, fmt.Errorf(\"field %q: %w\", field.Key, err)
\t\t}
\t\tbuf = append(buf, val...)
\t}
\tbuf = append(buf, '}')
\treturn buf, nil
}

func main() {
\tenc := json.NewEncoder(os.Stdout)
\tenc.SetEscapeHTML(false)
\tif err := enc.Encode(workflow()); err != nil {
\t\tfmt.Fprintln(os.Stderr, \"loopt: failed to encode workflow:\", err)
\t\tos.Exit(1)
\t}
}
";

const INDENT: &str = "\t";

/// Emits a standalone `<stem>.go` program that reconstructs `workflow` as
/// ordered native Go values and prints it to stdout as one JSON object.
pub fn emit(workflow: &Value, stem: &Path) -> Result<GeneratedSource> {
    let entrypoint = go_entrypoint(stem)?;

    let mut source = String::with_capacity(HEADER.len() + RUNTIME.len() + 256);
    source.push_str(HEADER);
    source.push_str("func workflow() interface{} {\n\treturn ");
    render_value(workflow, 1, &mut source);
    source.push_str("\n}\n");
    source.push_str(RUNTIME);

    Ok(GeneratedSource {
        entrypoint: entrypoint.clone(),
        files: vec![GeneratedFile {
            path: entrypoint,
            content: source,
        }],
    })
}

/// Returns the command to run a previously emitted `<source>.go` file:
/// `go run <source>`, executed with no shell and no external modules, from
/// the repository root.
pub fn command(source: &Path) -> Result<CommandSpec> {
    match source.extension().and_then(|ext| ext.to_str()) {
        Some("go") => {}
        _ => bail!("go: expected a .go source file, got {}", source.display()),
    }
    let arg = source
        .to_str()
        .with_context(|| format!("go: source path is not valid UTF-8: {}", source.display()))?
        .to_string();
    Ok(CommandSpec {
        program: "go".to_string(),
        args: vec!["run".to_string(), arg],
    })
}

/// Appends `.go` to `stem` to get the entrypoint path, without disturbing
/// any dot already present in the stem's final component.
fn go_entrypoint(stem: &Path) -> Result<PathBuf> {
    let mut os_string = stem.as_os_str().to_os_string();
    if os_string.is_empty() {
        bail!("go: workflow stem must not be empty");
    }
    os_string.push(".go");
    Ok(PathBuf::from(os_string))
}

fn render_value(value: &Value, depth: usize, out: &mut String) {
    match value {
        Value::Null => out.push_str("nil"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => render_number(n, out),
        Value::String(s) => render_string(s, out),
        Value::Array(items) => render_array(items, depth, out),
        Value::Object(map) => render_object(map, depth, out),
    }
}

/// Renders a JSON number as a Go numeric literal. Values that fit `i64`
/// (Go's default `int` is 64-bit on every platform Loopt targets) are
/// emitted as plain literals; values that only fit `u64` are given an
/// explicit `uint64(...)` conversion so the full unsigned range survives
/// without overflowing Go's untyped-constant default type. `serde_json`'s
/// number text is already valid Go numeral syntax (JSON numeral grammar is
/// a subset of Go's), so floats are emitted verbatim.
fn render_number(n: &Number, out: &mut String) {
    if n.as_u64().is_some() && n.as_i64().is_none() {
        out.push_str("uint64(");
        out.push_str(&n.to_string());
        out.push(')');
        return;
    }
    out.push_str(&n.to_string());
}

/// Renders a JSON string as a Go string literal. Prefers a raw
/// (backtick-delimited) literal when safe -- the common case for
/// multi-line shell scripts, which then read as an actual multi-line
/// block instead of a wall of `\n` escapes. Falls back to an interpreted
/// literal (escaping control characters) whenever the content contains a
/// backtick or carriage return, both of which raw literals cannot
/// represent exactly (Go strips `\r` from raw literals, and a literal
/// backtick would terminate them early). Ordinary Unicode text is kept as
/// literal UTF-8 either way.
fn render_string(s: &str, out: &mut String) {
    if can_use_raw_literal(s) {
        out.push('`');
        out.push_str(s);
        out.push('`');
    } else {
        render_interpreted_string(s, out);
    }
}

fn can_use_raw_literal(s: &str) -> bool {
    !s.contains('`') && !s.contains('\r')
}

fn render_interpreted_string(s: &str, out: &mut String) {
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

fn render_array(items: &[Value], depth: usize, out: &mut String) {
    if items.is_empty() {
        out.push_str("[]interface{}{}");
        return;
    }
    out.push_str("[]interface{}{\n");
    for item in items {
        push_indent(out, depth + 1);
        render_value(item, depth + 1, out);
        out.push_str(",\n");
    }
    push_indent(out, depth);
    out.push('}');
}

fn render_object(map: &Map<String, Value>, depth: usize, out: &mut String) {
    if map.is_empty() {
        out.push_str("newOM()");
        return;
    }
    out.push_str("newOM(\n");
    for (key, value) in map {
        push_indent(out, depth + 1);
        out.push_str("f(");
        render_string(key, out);
        out.push_str(", ");
        render_value(value, depth + 1, out);
        out.push_str("),\n");
    }
    push_indent(out, depth);
    out.push(')');
}

fn push_indent(out: &mut String, depth: usize) {
    for _ in 0..depth {
        out.push_str(INDENT);
    }
}
