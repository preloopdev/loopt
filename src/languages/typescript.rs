//! TypeScript language integration.
//!
//! `emit` turns a parsed GitHub Actions workflow (`serde_json::Value`) into a
//! standalone, human-editable TypeScript source file that *constructs* the
//! same value as native TypeScript data (object/array literals, strings,
//! numbers, booleans, `null`) and prints it back out as one JSON object on
//! stdout. Nothing is embedded as an opaque JSON/YAML string: every scalar,
//! key and nesting level is a real literal a user can edit, loop over, or
//! wrap in helper functions.
//!
//! Node's native TypeScript support only *strips* type syntax -- it never
//! transforms it -- so the generated runtime prelude avoids any
//! non-erasable construct (enums, namespaces, parameter properties, ...)
//! and sticks to plain `interface`/`type` annotations, ordinary classes with
//! explicit field declarations, and `as` assertions.
//!
//! Two JS-specific pitfalls get explicit handling that the other language
//! backends do not need:
//!
//!   - **Key order for numeric-looking keys.** Plain JS object literals
//!     silently reorder own keys that look like array indices ("0", "1",
//!     ...) ahead of every other key, regardless of insertion order. Any
//!     object containing such a key is emitted through an `ordered([[key,
//!     value], ...])` helper backed by an array of entries instead, which
//!     is immune to that reordering.
//!   - **Integer precision.** JS `number` cannot exactly represent integers
//!     outside +/-2^53 (`Number.MAX_SAFE_INTEGER`). Integers outside that
//!     range are emitted via a `raw("exact decimal text")` helper that
//!     carries the value through as text instead of a `number`.
//!
//! `__proto__`-named keys are emitted with computed-property syntax
//! (`["__proto__"]: value`), which creates a normal own data property
//! instead of triggering the legacy Annex B `__proto__`-in-object-literal
//! behavior that would otherwise reassign the object's prototype.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{bail, Context, Result};
use serde_json::{Number, Value};

use crate::languages::{CommandSpec, GeneratedFile, GeneratedSource};

const INDENT: &str = "  ";

/// The largest magnitude integer that round-trips through a JS `number`
/// without losing precision (`Number.MAX_SAFE_INTEGER`).
const MAX_SAFE_INTEGER: u64 = 9_007_199_254_740_991;

/// Build the TypeScript source for `workflow`, returning a single-file
/// `GeneratedSource` rooted at `<stem>.ts`.
pub fn emit(workflow: &Value, stem: &Path) -> Result<GeneratedSource> {
    let mut literal = String::new();
    write_value(&mut literal, workflow, 1)?;

    let entrypoint = stem.with_extension("ts");
    let content = render_module(&literal);

    Ok(GeneratedSource {
        entrypoint: entrypoint.clone(),
        files: vec![GeneratedFile {
            path: entrypoint,
            content,
        }],
    })
}

/// Describe how to execute a previously generated TypeScript source file.
/// Node (22.6+, unconditionally since 23.6) strips TypeScript type syntax
/// natively for `.ts` files with no flag and no separate build step.
pub fn command(source: &Path) -> Result<CommandSpec> {
    let path = source
        .to_str()
        .with_context(|| format!("source path {} is not valid UTF-8", source.display()))?
        .to_string();

    Ok(CommandSpec {
        program: "node".to_string(),
        args: vec![path],
        env: Vec::new(),
    })
}

/// Wrap the top-level TypeScript literal in an editable module: the runtime
/// prelude (`JsonValue` type, `ordered`/`raw` helpers, the hand-rolled
/// order-preserving `stringify`), the literal itself bound to `workflow`,
/// and a final write of exactly one JSON object to stdout.
fn render_module(literal: &str) -> String {
    format!(
        "{MODULE_HEADER}\n\nconst workflow: JsonValue = {literal};\n\nprocess.stdout.write(stringify(workflow) + '\\n');\n"
    )
}

const MODULE_HEADER: &str = r#"/**
 * Generated by `loopt import`.
 *
 * This file *is* the workflow: every job, step, and value below is an
 * ordinary TypeScript object/array/string/number/boolean literal that you
 * can edit, loop over, or build with helper functions -- add imports,
 * functions, or loops above `const workflow` as needed. Running `loopt gen`
 * executes this file with Node's built-in TypeScript support and turns
 * whatever JSON object it prints on stdout back into workflow YAML.
 *
 * Two small helpers keep that round trip exact in the two places a plain
 * JavaScript value cannot represent the original faithfully:
 *
 *   - `ordered([[key, value], ...])` builds an object whose entries keep
 *     exactly the order they are written in, even when some keys are
 *     purely numeric ("0", "1", ...). Plain object literals silently
 *     reorder such keys ahead of every other key no matter how they were
 *     inserted, which would corrupt a workflow map that happens to use
 *     numeric-looking keys (e.g. a hand-written matrix axis).
 *   - `raw("1234567890123456789")` embeds an integer too large to
 *     round-trip through a JS `number` (outside +/-2^53) using its exact
 *     decimal text, so no precision is lost.
 *
 * You will not need either helper for most edits -- use plain object and
 * array literals everywhere else.
 */

type JsonValue =
  | string
  | number
  | boolean
  | null
  | RawNumber
  | OrderedObject
  | JsonValue[]
  | { [key: string]: JsonValue };

/** An integer literal preserved verbatim because it exceeds JS's safe integer range. */
class RawNumber {
  readonly literal: string;
  constructor(literal: string) {
    this.literal = literal;
  }
}

/** An object whose entries keep exactly the order they were written in. */
class OrderedObject {
  readonly entries: [string, JsonValue][];
  constructor(entries: [string, JsonValue][]) {
    this.entries = entries;
  }
}

function raw(literal: string): RawNumber {
  return new RawNumber(literal);
}

function ordered(entries: [string, JsonValue][]): OrderedObject {
  return new OrderedObject(entries);
}

/** Escape `value` as a double-quoted JSON string literal (also valid JS syntax). */
function jsonString(value: string): string {
  let out = '"';
  for (const ch of value) {
    const code = ch.codePointAt(0) ?? 0;
    switch (ch) {
      case '"':
        out += '\\"';
        break;
      case '\\':
        out += '\\\\';
        break;
      case '\n':
        out += '\\n';
        break;
      case '\r':
        out += '\\r';
        break;
      case '\t':
        out += '\\t';
        break;
      case '\b':
        out += '\\b';
        break;
      case '\f':
        out += '\\f';
        break;
      default:
        if (code < 0x20) {
          out += '\\u' + code.toString(16).padStart(4, '0');
        } else {
          out += ch;
        }
    }
  }
  return out + '"';
}

/**
 * Serialize `value` to JSON text, honoring `OrderedObject` entry order and
 * `RawNumber` exact-text integers. Plain object literals are safe to walk
 * with `Object.keys` here because every object this file constructs with
 * numeric-looking keys goes through `ordered(...)` instead -- see the
 * module doc comment above.
 */
function stringify(value: JsonValue): string {
  if (value === null) {
    return 'null';
  }
  if (typeof value === 'string') {
    return jsonString(value);
  }
  if (typeof value === 'boolean') {
    return value ? 'true' : 'false';
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) {
      throw new Error('workflow contains a non-finite number, which has no JSON representation');
    }
    return String(value);
  }
  if (value instanceof RawNumber) {
    return value.literal;
  }
  if (value instanceof OrderedObject) {
    return (
      '{' +
      value.entries.map(([key, entry]) => jsonString(key) + ':' + stringify(entry)).join(',') +
      '}'
    );
  }
  if (Array.isArray(value)) {
    return '[' + value.map(stringify).join(',') + ']';
  }
  const keys = Object.keys(value);
  return '{' + keys.map((key) => jsonString(key) + ':' + stringify(value[key])).join(',') + '}';
}"#;

/// Recursively render `value` as a TypeScript literal. `indent` is the
/// nesting depth (in `INDENT` units) of the *contents* of the literal being
/// written; the returned text has no leading indentation of its own so the
/// caller can splice it directly after `const workflow: JsonValue = `,
/// `key: `, or inside an array/`ordered([...])` call.
fn write_value(out: &mut String, value: &Value, indent: usize) -> Result<()> {
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => out.push_str(&format_number(n)?),
        Value::String(s) => out.push_str(&ts_string_literal(s)),
        Value::Array(items) => write_array(out, items, indent)?,
        Value::Object(map) => write_object(out, map, indent)?,
    }
    Ok(())
}

fn write_array(out: &mut String, items: &[Value], indent: usize) -> Result<()> {
    if items.is_empty() {
        out.push_str("[]");
        return Ok(());
    }
    let pad = INDENT.repeat(indent);
    let pad_outer = INDENT.repeat(indent.saturating_sub(1));
    out.push_str("[\n");
    for item in items {
        out.push_str(&pad);
        write_value(out, item, indent + 1)?;
        out.push_str(",\n");
    }
    out.push_str(&pad_outer);
    out.push(']');
    Ok(())
}

/// Render `map` as a TypeScript object literal, or -- if any key looks like
/// an array index -- route the whole object through the order-preserving
/// `ordered([...])` helper instead, since a plain object literal would
/// silently reorder such keys ahead of the rest regardless of how this
/// code writes them.
fn write_object(
    out: &mut String,
    map: &serde_json::Map<String, Value>,
    indent: usize,
) -> Result<()> {
    if map.is_empty() {
        out.push_str("{}");
        return Ok(());
    }
    if map.keys().any(|key| is_array_index_like(key)) {
        return write_ordered_object(out, map, indent);
    }

    let pad = INDENT.repeat(indent);
    let pad_outer = INDENT.repeat(indent.saturating_sub(1));
    out.push_str("{\n");
    for (key, val) in map {
        out.push_str(&pad);
        out.push_str(&render_object_key(key));
        out.push_str(": ");
        write_value(out, val, indent + 1)?;
        out.push_str(",\n");
    }
    out.push_str(&pad_outer);
    out.push('}');
    Ok(())
}

fn write_ordered_object(
    out: &mut String,
    map: &serde_json::Map<String, Value>,
    indent: usize,
) -> Result<()> {
    let pad = INDENT.repeat(indent + 1);
    let pad_outer = INDENT.repeat(indent);
    out.push_str("ordered([\n");
    for (key, val) in map {
        out.push_str(&pad);
        out.push('[');
        out.push_str(&ts_string_literal(key));
        out.push_str(", ");
        write_value(out, val, indent + 2)?;
        out.push_str("],\n");
    }
    out.push_str(&pad_outer);
    out.push_str("])");
    Ok(())
}

/// Render an object key as it should appear before `: value` in a plain
/// object literal: bare if it is a safe identifier, a quoted string
/// literal otherwise -- except `__proto__`, which always uses computed
/// syntax (`["__proto__"]`) so it defines a normal own property instead of
/// triggering the legacy Annex B behavior that reassigns the prototype.
fn render_object_key(key: &str) -> String {
    if key == "__proto__" {
        format!("[{}]", ts_string_literal(key))
    } else if is_valid_identifier(key) {
        key.to_string()
    } else {
        ts_string_literal(key)
    }
}

/// A conservative, ASCII-only identifier check: enough to decide whether a
/// key is safe to emit bare. Anything else (including non-ASCII, which is
/// technically legal in a JS identifier but not worth the complexity here)
/// falls back to a quoted string key, which is always valid.
fn is_valid_identifier(key: &str) -> bool {
    let mut chars = key.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

/// Whether `key`, as a JS property key, would be treated as an array index
/// and therefore reordered ahead of other keys by a plain object literal:
/// a canonical (no leading zero, "0" itself excepted) decimal integer
/// string in `[0, 2^32 - 2]` (the valid array index range per the
/// ECMAScript spec; `2^32 - 1` itself is reserved as the max array length
/// and is not an index).
fn is_array_index_like(key: &str) -> bool {
    if key.is_empty() || !key.bytes().all(|b| b.is_ascii_digit()) {
        return false;
    }
    if key.len() > 1 && key.starts_with('0') {
        return false;
    }
    match key.parse::<u32>() {
        Ok(n) => n != u32::MAX,
        Err(_) => false,
    }
}

/// Render a JSON number as a TypeScript literal, preserving exact integer
/// precision: integers that fit within `Number.MAX_SAFE_INTEGER` stay plain
/// numeric literals, integers outside that range go through `raw(...)` with
/// their exact decimal text. Integer-valued floats also use `raw(...)` so
/// their authored `.0`/exponent spelling survives the final serializer
/// (JavaScript's `number` type otherwise collapses `5.0` to `5`). Other
/// finite floats use Rust's shortest round-trip decimal formatting, which
/// matches the same guarantee ECMAScript's `Number::toString` makes -- so
/// the literal parses back to a bit-identical JS number.
fn format_number(n: &Number) -> Result<String> {
    if let Some(i) = n.as_i64() {
        return Ok(format_integer(
            &i.to_string(),
            i.unsigned_abs() <= MAX_SAFE_INTEGER,
        ));
    }
    if let Some(u) = n.as_u64() {
        return Ok(format_integer(&u.to_string(), u <= MAX_SAFE_INTEGER));
    }
    // With serde_json's `arbitrary_precision` feature, a decimal integer
    // beyond u64 may still be represented exactly by Number even though
    // `as_f64()` would offer a lossy approximation. Detect that textual
    // shape before considering the float path.
    let text = n.to_string();
    let digits = text.strip_prefix('-').unwrap_or(&text);
    if !digits.is_empty() && digits.bytes().all(|byte| byte.is_ascii_digit()) {
        return Ok(format!("raw({})", ts_string_literal(&text)));
    }
    if let Some(f) = n.as_f64() {
        return format_float(f);
    }
    // Only reachable with serde_json's `arbitrary_precision` feature, where
    // a number that overflowed i64/u64/f64 is kept as exact decimal text;
    // route it through `raw()` so no precision is ever silently lost.
    Ok(format!("raw({})", ts_string_literal(&text)))
}

fn format_integer(text: &str, fits_in_js_number: bool) -> String {
    if fits_in_js_number {
        text.to_string()
    } else {
        format!("raw({})", ts_string_literal(text))
    }
}

fn format_float(f: f64) -> Result<String> {
    if !f.is_finite() {
        bail!("workflow contains a non-finite number ({f}), which has no JSON representation");
    }
    let repr = format!("{f:?}");
    if f.fract() == 0.0 {
        // Once a JS number is constructed, `String(5.0)` is just `"5"`.
        // Carry integer-valued floats through the same exact-text wrapper
        // used for oversized integers so the emitted JSON retains `5.0`
        // (and forms such as `1e20`) rather than silently changing spelling.
        return Ok(format!("raw({})", ts_string_literal(&repr)));
    }
    Ok(repr)
}

/// Render `s` as a double-quoted TypeScript string literal using JSON's
/// escaping rules (JSON string syntax is valid JS string syntax): escape
/// `"`, `\`, and control characters; everything else -- including printable
/// Unicode -- is emitted verbatim since generated sources are UTF-8 files
/// and modern JS string literals permit raw U+2028/U+2029 and above.
fn ts_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
